namespace NightDuty
{
    /// <summary>
    /// 순찰 대상 공간 식별자.
    /// 근무수칙(RuleSO)과 공간 프로필(SpaceProfileSO)이 모두 이 값으로 공간을 지목한다.
    /// 8주 스코프 절단 이후 채택된 4개 공간 / 5개 순찰 지점만 정의한다.
    /// (도서관·탈의실은 "2차 풀"로 보류된 상태이므로 여기에 없다. 되살릴 때 값을 이어 붙일 것.)
    /// 명시적 숫자를 박아 두는 이유: 이 값이 .asset(ScriptableObject)에 직렬화되므로
    /// 열거자 순서를 바꾸면 기존 데이터의 의미가 통째로 어긋난다.
    /// </summary>
    public enum SpaceId
    {
        /// <summary>미지정. 기본값이자 "아직 어떤 공간도 아니다"라는 뜻. 유효한 순찰 지점이 아니다.</summary>
        None = 0,

        /// <summary>
        /// 복도. 자기보고(self-reporting) 공간 — 플레이어가 공포 지표를 읽는 법을 배우는 곳이다.
        /// 점등된 형광등 개수(8개 중) = 조도 축, 밖에 나와 있는 집기 = 배치 축, 문 소리 = 청각 축.
        /// </summary>
        Corridor = 1,

        /// <summary>화장실. 칸막이 4칸. 각 칸의 문은 HingedDoor 컴포넌트를 쓴다.</summary>
        Toilet = 2,

        /// <summary>교실 1-1. 교실 프리팹은 1-3과 동일하고 상태 값만 다르다.</summary>
        Classroom_1_1 = 3,

        /// <summary>교실 1-3. 교실 프리팹은 1-1과 동일하고 상태 값만 다르다.</summary>
        Classroom_1_3 = 4,

        /// <summary>
        /// 과학실. 인체 모형 하나를 추적하는 단일 오브젝트 공간.
        /// 조도 90~100 구간에서도 완전 암전이 아니라 최소한의 붉은 잔광을 남긴다.
        /// (손전등을 끈 채 모형을 응시해야 하는 수칙이 두 개 있기 때문이다.)
        /// </summary>
        ScienceRoom = 5
    }

    /// <summary>
    /// 공포 축. 각 축은 0~100 범위의 정수 값을 가지며 5개 구간(<see cref="Band"/>)으로 나뉜다.
    /// 청각·조도·배치 세 축은 월드의 연출을 직접 구동하고,
    /// 신뢰 축만은 월드가 아니라 인게임 지침록(문서)을 구동한다.
    /// </summary>
    public enum FearAxis
    {
        /// <summary>
        /// 청각(廳覺). 문 여닫는 소리, 발소리, 정체 불명의 소음 등 사운드 연출 밀도를 결정한다.
        /// </summary>
        Auditory = 0,

        /// <summary>
        /// 조도(照度). 점등된 형광등 개수와 색온도를 결정한다.
        /// 개수/색온도 표는 전 공간 공용이며, 공간별 파라미터는 등기구 개수뿐이다
        /// (복도 8 / 교실 8 / 화장실 4 / 과학실 4).
        /// 75 이상은 "붉게 보인다" 판정(<see cref="Bands.RedThreshold"/>)에 걸린다.
        /// </summary>
        Illuminance = 1,

        /// <summary>
        /// 배치(配置). 집기·소품이 제자리에 있는지, 문이 열려 있는지 등 오브젝트 상태를 결정한다.
        /// 미방문 공간 페널티(+22)도 이 축에 들어간다.
        /// </summary>
        Layout = 2,

        /// <summary>
        /// 신뢰(信賴). 다른 세 축과 달리 월드에 절대 그려지지 않는다.
        /// 대신 인게임 지침록(근무 지침 문서)의 문구·누락·자기모순을 구동한다.
        /// 연출 코드가 이 축을 보고 월드를 바꾸려 한다면 그건 설계 위반이다.
        /// </summary>
        Trust = 3
    }

    /// <summary>
    /// 공포 축 값이 속하는 구간. 폭이 균일하지 않다는 점에 주의할 것.
    /// Band0 = 0~24, Band1 = 25~49, Band2 = 50~74, Band3 = 75~89, Band4 = 90~100
    /// (Band3은 15칸, Band4는 11칸으로 뒤로 갈수록 좁아진다 — 고조 구간을 잘게 쪼개기 위한 의도적 설계다.)
    /// 실제 범위 표는 <see cref="Bands"/>에 한 곳으로 모아 두었다.
    /// </summary>
    public enum Band
    {
        /// <summary>0~24. 평상. 이상 징후가 사실상 없다.</summary>
        Band0 = 0,

        /// <summary>25~49. 미약한 위화감.</summary>
        Band1 = 1,

        /// <summary>50~74. 명백한 이상. 조도 축에서는 "붉어 보이지만 붉음 판정은 아닌" 회색지대(3200K)다.</summary>
        Band2 = 2,

        /// <summary>75~89. 고조. 조도 축이 이 구간에 들면 "붉게 보인다" 판정이 성립한다.</summary>
        Band3 = 3,

        /// <summary>90~100. 임계. 축이 100에 도달하면 <c>EventBus.AxisCritical</c>이 발생한다.</summary>
        Band4 = 4
    }
}
